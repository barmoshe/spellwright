// data/catalog.js — typed views over the designer's data (loaded verbatim by core/db.js). PURE: no
// Phaser, usable from node. One place that knows table shapes, so gameplay code reads `CAT.cards.fireball`,
// `CAT.rules.casting.maxShotsPerCast`, `CAT.economy.prices`, never raw JSON paths.
//
// Conventions (mechanic-spec §0): spells + modifiers share one card-id namespace → CAT.cards.
// Time stays in ms in the catalogue; systems convert to sim steps once via toSteps().

const byId = (list) => Object.fromEntries((list || []).map((r) => [r.id, r]));

export function buildCatalog(tables) {
  const T = (name) => (tables[name] ? tables[name].list || tables[name] : []);
  const spells = T('spells'), modifiers = T('modifiers');
  const cards = { ...byId(spells), ...byId(modifiers) };
  const rules = byId(T('rules'));
  const economy = byId(T('economy'));
  const floors = T('floors');
  const cat = {
    cards,
    cardList: [...spells, ...modifiers],
    spells: byId(spells),
    modifiers: byId(modifiers),
    wands: byId(T('wands')),
    wandList: T('wands'),
    relics: byId(T('relics')),
    relicList: T('relics'),
    enemies: byId(T('enemies')),
    bosses: byId(T('bosses')),
    rooms: byId(T('rooms')),
    floors: byId(floors),
    floorList: floors.slice().sort((a, b) => (a.index ?? a.floor ?? 0) - (b.index ?? b.floor ?? 0)),
    rules,
    economy,
    unlocks: T('unlocks'),
    loadouts: byId(T('loadouts')),
    loadoutList: T('loadouts'),
    roomsMeta: tables.rooms && tables.rooms.meta ? tables.rooms.meta : {},
    // v2 tables (design-v2; Wave D): forge recipes (merge / evolve / slot), modes (standard / gentle / daily), elite affixes
    forge: byId(T('forge')),
    forgeList: T('forge'),
    modes: byId(T('modes')),
    affixes: byId(T('affixes')),
    affixList: T('affixes'),
  };
  // Duo relics: { parentA+parentB } views (economy duo weight; offered only when both parents are owned)
  cat.duoList = cat.relicList.filter((r) => r.duo && Array.isArray(r.duo.parents) && r.duo.parents.length === 2);
  // Forge views (forge.json; design-v2 §9): merge recipes by source card, evolve recipes by base, the slot record
  cat.forgeMerges = cat.forgeList.filter((r) => r.type === 'merge');
  cat.forgeEvolves = cat.forgeList.filter((r) => r.type === 'evolve');
  cat.forgeSlot = cat.forgeList.find((r) => r.type === 'slot') || null;
  cat.mergeByFrom = Object.fromEntries(cat.forgeMerges.map((r) => [r.from, r]));
  cat.evolveByBase = Object.fromEntries(cat.forgeEvolves.map((r) => [r.base, r]));
  // Relic pools by category (corrupted: risk door only; duo: both parents owned only)
  cat.corruptedList = cat.relicList.filter((r) => r.category === 'corrupted' || r.rarity === 'corrupted');
  // Every id named in any unlocks[].unlocks is locked at first launch (progression §7).
  const locked = { cards: new Set(), wands: new Set(), relics: new Set(), loadouts: new Set(), features: new Set() };
  for (const u of cat.unlocks) for (const k of Object.keys(locked)) for (const id of (u.unlocks && u.unlocks[k]) || []) locked[k].add(id);
  cat.lockedByDefault = locked;
  return cat;
}

/** A card's defence-breaking / descriptive keywords (data-generated by build.py: the single source). */
export const keywordsOf = (c, id) => ((c.cards[id] || c.relics[id] || {}).keywords || []);
/** Duo relics whose two parents are both in `ownedRelicIds` and which aren't owned yet. */
export const duosFor = (c, ownedRelicIds) => {
  const own = new Set(ownedRelicIds || []);
  return c.duoList.filter((d) => !own.has(d.id) && d.duo.parents.every((p) => own.has(p)));
};

/** A card never offered by drafts / shops / crates (level-2 and evolved cards: forge-only, systems §11). */
export const isForgeOnly = (c, id) => { const r = c.cards[id]; return !!r && (r.pool === false || (r.level | 0) >= 2 || r.rarity === 'evolved'); };
/** A relic that the ordinary relic pool may offer (not duo, not corrupted). */
export const isPlainRelic = (r) => !!r && r.category !== 'duo' && r.category !== 'corrupted' && r.rarity !== 'duo' && r.rarity !== 'corrupted';

/** The castWand env's `rules` subset. */
export const castRules = (cat) => ({ casting: cat.rules.casting, crit: cat.rules.crit, shotClamps: cat.rules.shotClamps });

export const CAT = { current: null };
export function setCatalog(c) { CAT.current = c; }
export function cat() { return CAT.current; }
